// Command gen writes protocol_gen.go from the committed sidecar protocol
// schema: a struct per plain definition, the constants of its x-srelens-*
// tables, and the rule of every patterned string field. It handles only the
// keywords that schema uses and refuses anything else, so a construct a later
// schema adds cannot be generated wrong without anyone noticing.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"sort"
	"strconv"
	"strings"
	"unicode"
)

type object = map[string]any

// handWritten are the definitions the protocol package writes by hand, and
// the Go type a $ref to each names ("" for the unions, which nothing refers
// to).
var handWritten = map[string]string{
	"HostMessage":    "",
	"SidecarMessage": "",
	"RequestId":      "RequestID",
}

// initialisms are the words Go spells in capitals.
var initialisms = map[string]string{"id": "ID", "api": "API", "uid": "UID", "rpc": "RPC", "cpus": "CPUs"}

var (
	rootKeywords = set("$id", "$schema", "anyOf", "definitions", "description", "title",
		"x-srelens-apiVersion", "x-srelens-errorCodes", "x-srelens-errorData", "x-srelens-maxMessageBytes", "x-srelens-methods")
	definitionKeywords = set("type", "properties", "required", "additionalProperties", "description")
	propertyKeywords   = set("type", "$ref", "anyOf", "items", "pattern", "minLength", "maxLength", "minimum", "minItems", "maxItems", "uniqueItems", "not", "description")
	methodKeywords     = set("direction", "kind", "params", "result")
)

func set(words ...string) map[string]bool {
	s := map[string]bool{}
	for _, w := range words {
		s[w] = true
	}
	return s
}

// goName is name in Go's exported spelling: "clusterId" is "ClusterID",
// "$/cancelRequest" is "CancelRequest", "RpcError" is "RPCError".
func goName(name string) string {
	var words []string
	var word []rune
	flush := func() {
		if len(word) > 0 {
			words = append(words, string(word))
			word = nil
		}
	}
	for _, r := range name {
		switch {
		case !unicode.IsLetter(r) && !unicode.IsDigit(r):
			flush()
		case unicode.IsUpper(r) && len(word) > 0 && !unicode.IsUpper(word[len(word)-1]):
			flush()
			word = append(word, r)
		default:
			word = append(word, r)
		}
	}
	flush()
	var out strings.Builder
	for _, w := range words {
		if up, ok := initialisms[strings.ToLower(w)]; ok {
			out.WriteString(up)
			continue
		}
		out.WriteString(strings.ToUpper(w[:1]) + w[1:])
	}
	return out.String()
}

func sortedKeys(o object) []string {
	keys := make([]string, 0, len(o))
	for k := range o {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// only refuses any keyword of o outside allowed.
func only(o object, allowed map[string]bool, path string) error {
	for _, k := range sortedKeys(o) {
		if !allowed[k] {
			return fmt.Errorf("%s: the generator does not support the keyword %q", path, k)
		}
	}
	return nil
}

// nested accepts a schema inside a property's anyOf or items: the keywords
// of a property, but not a pattern, which shapes reads only at a property's
// top level.
func nested(o object, path string) error {
	if err := only(o, propertyKeywords, path); err != nil {
		return err
	}
	if _, ok := o["pattern"]; ok && !(strings.HasSuffix(path, ".items") && o["type"] == "string") {
		return fmt.Errorf("%s: a pattern is supported only at a property's top level", path)
	}
	return nil
}

func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }

// generate is protocol_gen.go for schema, gofmt'd.
func generate(schema []byte) ([]byte, error) {
	dec := json.NewDecoder(bytes.NewReader(schema))
	dec.UseNumber()
	var root object
	if err := dec.Decode(&root); err != nil {
		return nil, fmt.Errorf("the schema is not a JSON object: %w", err)
	}
	g := &generator{root: root}
	if err := g.run(); err != nil {
		return nil, err
	}
	src, err := format.Source(g.out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("the generated file does not parse: %w\n%s", err, g.out.Bytes())
	}
	return src, nil
}

type generator struct {
	root object
	defs object
	out  bytes.Buffer
}

func (g *generator) printf(format string, args ...any) { fmt.Fprintf(&g.out, format, args...) }

func (g *generator) run() error {
	if err := only(g.root, rootKeywords, "the schema's root"); err != nil {
		return err
	}
	defs, ok := g.root["definitions"].(object)
	if !ok {
		return fmt.Errorf("the schema has no definitions")
	}
	g.defs = defs
	for _, name := range sortedKeys(object{"HostMessage": nil, "SidecarMessage": nil, "RequestId": nil}) {
		if _, ok := defs[name]; !ok {
			return fmt.Errorf("definitions.%s is missing", name)
		}
	}
	g.printf("// Code generated by sdk/go/internal/gen from the committed sidecar protocol schema. DO NOT EDIT.\n\n")
	g.printf("package protocol\n\nimport (\n\t\"encoding/json\"\n\t\"regexp\"\n)\n\n")
	if err := g.constants(); err != nil {
		return err
	}
	for _, name := range sortedKeys(defs) {
		if _, skip := handWritten[name]; skip {
			continue
		}
		if err := g.definition(name, defs[name]); err != nil {
			return err
		}
	}
	return g.shapes()
}

func (g *generator) constants() error {
	version, ok := g.root["x-srelens-apiVersion"].(string)
	if !ok {
		return fmt.Errorf("x-srelens-apiVersion is missing")
	}
	maxBytes, ok := g.root["x-srelens-maxMessageBytes"].(json.Number)
	if !ok {
		return fmt.Errorf("x-srelens-maxMessageBytes is missing")
	}
	codes, ok := g.root["x-srelens-errorCodes"].(object)
	if !ok {
		return fmt.Errorf("x-srelens-errorCodes is missing")
	}
	methods, ok := g.root["x-srelens-methods"].(object)
	if !ok {
		return fmt.Errorf("x-srelens-methods is missing")
	}
	g.printf("// APIVersion is the sidecar API version this file was generated for.\nconst APIVersion = %q\n\n", version)
	g.printf("// MaxMessageBytes is the longest line either side may write, not counting its line ending.\nconst MaxMessageBytes = %s\n\n", maxBytes)
	g.printf("// The JSON-RPC error codes the protocol uses.\nconst (\n")
	for _, name := range sortedKeys(codes) {
		code, ok := codes[name].(json.Number)
		if !ok {
			return fmt.Errorf("x-srelens-errorCodes.%s is not a number", name)
		}
		g.printf("\tCode%s = %s\n", goName(name), code)
	}
	g.printf(")\n\n")
	if data, ok := g.root["x-srelens-errorData"].(object); ok {
		for _, name := range sortedKeys(data) {
			if _, ok := codes[name]; !ok {
				return fmt.Errorf("x-srelens-errorData.%s names no error code", name)
			}
			if err := g.checkRef(data[name], "x-srelens-errorData."+name); err != nil {
				return err
			}
		}
	}
	g.printf("// The protocol's methods.\nconst (\n")
	for _, name := range sortedKeys(methods) {
		g.printf("\tMethod%s = %q\n", goName(name), name)
	}
	g.printf(")\n\n")
	g.printf("// MethodDirections is who sends each method: \"hostToSidecar\", \"sidecarToHost\" or \"both\".\n")
	g.printf("var MethodDirections = map[string]string{\n")
	for _, name := range sortedKeys(methods) {
		spec, ok := methods[name].(object)
		if !ok {
			return fmt.Errorf("x-srelens-methods.%s is not an object", name)
		}
		if err := only(spec, methodKeywords, "x-srelens-methods."+name); err != nil {
			return err
		}
		direction, _ := spec["direction"].(string)
		switch direction {
		case "hostToSidecar", "sidecarToHost", "both":
		default:
			return fmt.Errorf("x-srelens-methods.%s: unknown direction %q", name, direction)
		}
		kind, _ := spec["kind"].(string)
		switch kind {
		case "request", "notification":
		default:
			return fmt.Errorf("x-srelens-methods.%s: unknown kind %q", name, kind)
		}
		for _, key := range []string{"params", "result"} {
			if ref, ok := spec[key]; ok {
				if err := g.checkRef(ref, "x-srelens-methods."+name+"."+key); err != nil {
					return err
				}
			}
		}
		g.printf("\t%q: %q,\n", name, direction)
	}
	g.printf("}\n\n")
	return nil
}

// checkRef accepts true (any value) or a $ref to a definition.
func (g *generator) checkRef(v any, path string) error {
	if v == true {
		return nil
	}
	o, ok := v.(object)
	if !ok {
		return fmt.Errorf("%s: expected true or a $ref", path)
	}
	_, err := g.refName(o, path)
	return err
}

// refName is the Go type a $ref names.
func (g *generator) refName(o object, path string) (string, error) {
	ref, _ := o["$ref"].(string)
	name, ok := strings.CutPrefix(ref, "#/definitions/")
	if !ok {
		return "", fmt.Errorf("%s: $ref %q is not a definition", path, ref)
	}
	if _, ok := g.defs[name]; !ok {
		return "", fmt.Errorf("%s: $ref %q names no definition", path, ref)
	}
	if goType, ok := handWritten[name]; ok {
		if goType == "" {
			return "", fmt.Errorf("%s: $ref %q names a message union", path, ref)
		}
		return goType, nil
	}
	return goName(name), nil
}

func (g *generator) definition(name string, v any) error {
	path := "definitions." + name
	def, ok := v.(object)
	if !ok {
		return fmt.Errorf("%s is not an object schema", path)
	}
	if err := only(def, definitionKeywords, path); err != nil {
		return err
	}
	if ap, ok := def["additionalProperties"]; ok && ap != false {
		return fmt.Errorf("%s: additionalProperties is supported only as false", path)
	}
	if def["type"] != "object" {
		return fmt.Errorf(`%s: type must be "object"`, path)
	}
	props, _ := def["properties"].(object)
	required := map[string]bool{}
	if list, ok := def["required"].([]any); ok {
		for _, r := range list {
			field, _ := r.(string)
			if _, ok := props[field]; !ok {
				return fmt.Errorf("%s requires %q, which it does not define", path, field)
			}
			required[field] = true
		}
	}
	if desc, ok := def["description"].(string); ok {
		g.printf("// %s: %s\n", goName(name), oneLine(desc))
	}
	g.printf("type %s struct {\n", goName(name))
	for _, prop := range sortedKeys(props) {
		propPath := path + ".properties." + prop
		typ, omit, err := g.fieldType(props[prop], required[prop], propPath)
		if err != nil {
			return err
		}
		if p, ok := props[prop].(object); ok {
			if desc, ok := p["description"].(string); ok {
				g.printf("\t// %s\n", oneLine(desc))
			}
		}
		tag := prop
		if omit {
			tag += ",omitempty"
		}
		g.printf("\t%s %s `json:%q`\n", goName(prop), typ, tag)
	}
	g.printf("}\n\n")
	return nil
}

// fieldType is the Go type of one property, and whether it is left out when
// empty. A property that may be null is a pointer, always written; one that
// is not required is a pointer (or a slice or raw value) left out when nil.
func (g *generator) fieldType(v any, required bool, path string) (string, bool, error) {
	if v == true {
		return "json.RawMessage", !required, nil
	}
	p, ok := v.(object)
	if !ok {
		return "", false, fmt.Errorf("%s: expected a schema object or true", path)
	}
	if err := only(p, propertyKeywords, path); err != nil {
		return "", false, err
	}
	if not, ok := p["not"]; ok {
		if err := checkNotEnum(not, path); err != nil {
			return "", false, err
		}
	}
	base, nullable, err := g.baseType(p, path)
	if err != nil {
		return "", false, err
	}
	switch {
	case nullable:
		return "*" + base, !required, nil
	case !required && !strings.HasPrefix(base, "[]") && base != "json.RawMessage":
		return "*" + base, true, nil
	default:
		return base, !required, nil
	}
}

// checkNotEnum accepts only {"enum": [strings]}: the object-name rule.
func checkNotEnum(v any, path string) error {
	o, ok := v.(object)
	if !ok || len(o) != 1 {
		return fmt.Errorf(`%s: "not" is supported only as {"enum": [...]}`, path)
	}
	list, ok := o["enum"].([]any)
	if !ok {
		return fmt.Errorf(`%s: "not" is supported only as {"enum": [...]}`, path)
	}
	for _, item := range list {
		if _, ok := item.(string); !ok {
			return fmt.Errorf(`%s: "not"'s enum holds only strings`, path)
		}
	}
	return nil
}

// baseType is a schema's Go type, and whether it may be null.
func (g *generator) baseType(p object, path string) (string, bool, error) {
	if _, ok := p["$ref"]; ok {
		name, err := g.refName(p, path)
		return name, false, err
	}
	if anyOf, ok := p["anyOf"].([]any); ok {
		// Only the nullable form: a schema and {"type": "null"}, in either order.
		var inner object
		nulls := 0
		for _, alt := range anyOf {
			o, ok := alt.(object)
			if !ok {
				return "", false, fmt.Errorf("%s: anyOf holds a non-object", path)
			}
			if o["type"] == "null" && len(o) == 1 {
				nulls++
				continue
			}
			inner = o
		}
		if len(anyOf) != 2 || nulls != 1 || inner == nil {
			return "", false, fmt.Errorf("%s: anyOf is supported only as a nullable type", path)
		}
		if err := nested(inner, path+".anyOf"); err != nil {
			return "", false, err
		}
		base, _, err := g.baseType(inner, path+".anyOf")
		return base, true, err
	}
	switch t := p["type"].(type) {
	case string:
		base, err := g.scalar(t, p, path)
		return base, false, err
	case []any:
		if len(t) == 2 && t[1] == "null" {
			if s, ok := t[0].(string); ok {
				base, err := g.scalar(s, p, path)
				return base, true, err
			}
		}
		return "", false, fmt.Errorf(`%s: a type list is supported only as [type, "null"]`, path)
	}
	return "", false, fmt.Errorf("%s: no type", path)
}

func (g *generator) scalar(t string, p object, path string) (string, error) {
	switch t {
	case "string":
		return "string", nil
	case "boolean":
		return "bool", nil
	case "number":
		return "float64", nil
	case "integer":
		if min, ok := p["minimum"].(json.Number); ok {
			f, err := min.Float64()
			if err != nil || f < 0 {
				return "", fmt.Errorf("%s: minimum %s is not supported", path, min)
			}
			return "uint64", nil
		}
		return "int64", nil
	case "array":
		items, ok := p["items"].(object)
		if !ok {
			return "", fmt.Errorf("%s: an array needs an items schema", path)
		}
		if err := nested(items, path+".items"); err != nil {
			return "", err
		}
		base, nullable, err := g.baseType(items, path+".items")
		if err != nil {
			return "", err
		}
		if nullable {
			base = "*" + base
		}
		return "[]" + base, nil
	}
	return "", fmt.Errorf("%s: type %q is not supported", path, t)
}

// shapes writes the rule of every string field with a pattern, keyed
// "Definition.property".
func (g *generator) shapes() error {
	arrays := make(object)
	g.printf("// fieldShapes are the rules the schema states for each patterned string field, keyed \"Definition.property\".\n")
	g.printf("var fieldShapes = map[string]fieldShape{\n")
	for _, name := range sortedKeys(g.defs) {
		if _, skip := handWritten[name]; skip {
			continue
		}
		def, _ := g.defs[name].(object)
		props, _ := def["properties"].(object)
		for _, prop := range sortedKeys(props) {
			p, ok := props[prop].(object)
			if !ok {
				continue
			}
			key := name + "." + prop
			if p["type"] == "array" {
				items, _ := p["items"].(object)
				if _, patterned := items["pattern"].(string); patterned {
					if _, ok := p["minItems"].(json.Number); !ok {
						return fmt.Errorf("definitions.%s.properties.%s.items: a patterned array needs minItems", name, prop)
					}
					if _, ok := p["maxItems"].(json.Number); !ok {
						return fmt.Errorf("definitions.%s.properties.%s.items: a patterned array needs maxItems", name, prop)
					}
					arrays[key] = p
					p = items
					key += ".items"
				}
			}
			pattern, ok := p["pattern"].(string)
			if !ok {
				continue
			}
			max, ok := p["maxLength"].(json.Number)
			if !ok {
				return fmt.Errorf("definitions.%s.properties.%s: a pattern needs a maxLength", name, prop)
			}
			var not []string
			if n, ok := p["not"].(object); ok {
				for _, v := range n["enum"].([]any) {
					not = append(not, v.(string))
				}
			}
			g.printf("\t%q: {pattern: regexp.MustCompile(%s), maxLength: %s, not: %#v},\n",
				key, strconv.Quote(pattern), max, not)
		}
	}
	g.printf("}\n\n")
	g.printf("// fieldShape is one string field's rule: at most maxLength bytes, matching pattern, and none of not.\n")
	g.printf("type fieldShape struct {\n\tpattern   *regexp.Regexp\n\tmaxLength int\n\tnot       []string\n}\n")
	g.printf("\n// arrayShapes bound patterned string arrays; their items use fieldShapes.\nvar arrayShapes = map[string]arrayShape{\n")
	for _, key := range sortedKeys(arrays) {
		p := arrays[key].(object)
		g.printf("%q: {min: %s, max: %s, unique: %t},\n", key, p["minItems"], p["maxItems"], p["uniqueItems"] == true)
	}
	g.printf("}\ntype arrayShape struct { min, max int; unique bool }\n")
	return nil
}
